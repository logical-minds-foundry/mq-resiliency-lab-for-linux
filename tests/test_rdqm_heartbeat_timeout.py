"""Pin the RDQM HA heartbeat timeout to IBM's VM recommendation (#1515).

IBM MQ 10.0 "Changing the heartbeat timeout for HA RDQM"
(https://www.ibm.com/docs/en/SSYHRD_10.0.0/configure/heartbeat_timeout.html) gives a
3 s default, recommends 10 s for VM configurations, and says how to change it: Pacemaker
maintenance mode on, edit corosync.conf on each node (``token``, plus per heartbeat link
``knet_ping_timeout`` = token/2, ``knet_ping_interval`` = token/20, ``knet_pong_count`` = 2),
restart corosync on each node, check ``totem.token`` with ``corosync-cmapctl``, maintenance
mode off.

These tests cover the corosync.conf editor (the rdqm-ha role's ``rdqm_corosync_heartbeat``
module) and the role's ordering, idempotency gate and fail-loud checks.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from typing import TYPE_CHECKING, Any

import pytest
import yaml

if TYPE_CHECKING:
    from types import ModuleType

REPO_ROOT = Path(__file__).resolve().parents[1]
ROLE = REPO_ROOT / "ansible" / "roles" / "rdqm-ha"
MODULE_PATH = ROLE / "library" / "rdqm_corosync_heartbeat.py"
TASKS = ROLE / "tasks" / "main.yml"
DEFAULTS = ROLE / "defaults" / "main.yml"

SOFTENERS = ("ignore_errors", "failed_when", "rescue")


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("rdqm_corosync_heartbeat", MODULE_PATH)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


hb = _load()

# The shape rdqmadm -c writes: knet transport, one heartbeat address per node, no token
# and no interface block (IBM: "You must add these new settings to corosync.conf manually").
RDQM_CONF = """\
# generated by rdqmadm
totem {
    version: 2
    cluster_name: rdqm_cluster
    transport: knet
    crypto_cipher: aes256
    crypto_hash: sha256
}

nodelist {
    node {
        ring0_addr: 172.16.1.31
        name: rdqm-a1
        nodeid: 1
    }
    node {
        ring0_addr: 172.16.1.32
        name: rdqm-a2
        nodeid: 2
    }
}

quorum {
    provider: corosync_votequorum
}
"""


def _section(text: str, path: tuple[str, ...], nth: int = 0) -> Any:
    return [s for s in hb.parse(text.splitlines()) if s.path == path][nth]


def _keys(text: str, path: tuple[str, ...], nth: int = 0) -> dict[str, str]:
    return {k: v for k, (_, v) in _section(text, path, nth).keys.items()}


# --- the corosync.conf editor -------------------------------------------------------


def test_ibm_values_are_derived_from_the_token() -> None:
    assert hb.heartbeat_values(10000) == {
        "knet_ping_timeout": "5000",
        "knet_ping_interval": "500",
        "knet_pong_count": "2",
    }


def test_rdqm_conf_gets_ibm_settings_for_link_0() -> None:
    out = hb.apply_heartbeat(RDQM_CONF, 10000)
    assert int(_keys(out, ("totem",))["token"]) == 10000
    assert _keys(out, ("totem", "interface")) == {
        "linknumber": "0",
        "knet_ping_timeout": "5000",
        "knet_ping_interval": "500",
        "knet_pong_count": "2",
    }
    # Everything rdqmadm wrote is kept, comments included.
    for line in RDQM_CONF.splitlines():
        assert line in out.splitlines()
    assert "    token: 10000" in out.splitlines()
    assert "        knet_pong_count: 2" in out.splitlines()


def test_editing_twice_changes_nothing() -> None:
    once = hb.apply_heartbeat(RDQM_CONF, 10000)
    assert hb.apply_heartbeat(once, 10000) == once


def test_existing_values_are_replaced_in_place() -> None:
    text = (
        "totem {\n  token: 3000\n  interface {\n    linknumber: 0\n"
        "    knet_ping_timeout: 1500\n  }\n}\n"
    )
    out = hb.apply_heartbeat(text, 10000)
    assert "  token: 10000" in out.splitlines()
    assert "    knet_ping_timeout: 5000" in out.splitlines()
    assert _keys(out, ("totem", "interface"))["knet_pong_count"] == "2"
    assert out.count("token:") == 1


def test_two_heartbeat_links_get_two_interface_blocks() -> None:
    text = (
        "totem {\n    version: 2\n}\nnodelist {\n    node {\n"
        "        ring0_addr: 10.0.0.1\n        ring1_addr: 10.0.1.1\n    }\n}\n"
    )
    out = hb.apply_heartbeat(text, 10000)
    assert hb.heartbeat_links(hb.parse(out.splitlines())) == [0, 1]
    first = _keys(out, ("totem", "interface"), 0)
    second = _keys(out, ("totem", "interface"), 1)
    assert {first["linknumber"], second["linknumber"]} == {"0", "1"}
    for block in (first, second):
        assert block["knet_ping_timeout"] == "5000"
        assert block["knet_ping_interval"] == "500"


def test_an_interface_without_linknumber_is_link_0() -> None:
    text = "totem {\n    interface {\n        knet_link_priority: 1\n    }\n}\n"
    out = hb.apply_heartbeat(text, 10000)
    assert out.count("interface {") == 1
    assert _keys(out, ("totem", "interface"))["knet_ping_interval"] == "500"


def test_an_interface_for_another_link_is_left_alone() -> None:
    text = "totem {\n    interface {\n        linknumber: 3\n    }\n}\n"
    out = hb.apply_heartbeat(text, 10000)
    assert _keys(out, ("totem", "interface"), 0) == {"linknumber": "3"}
    assert _keys(out, ("totem", "interface"), 1)["linknumber"] == "0"


def test_an_empty_totem_is_indented_one_step() -> None:
    out = hb.apply_heartbeat("totem {\n}\n", 10000)
    assert "    token: 10000" in out.splitlines()
    assert "        knet_ping_timeout: 5000" in out.splitlines()


def test_a_totem_of_blank_lines_is_indented_one_step() -> None:
    out = hb.apply_heartbeat("totem {\n\n}\n", 10000)
    assert "    token: 10000" in out.splitlines()


@pytest.mark.parametrize("token", [2999, 120001])
def test_a_token_outside_ibms_range_is_refused(token: int) -> None:
    with pytest.raises(hb.CorosyncConfError, match="outside IBM's range"):
        hb.apply_heartbeat(RDQM_CONF, token)


@pytest.mark.parametrize(
    ("text", "match"),
    [
        ("quorum {\n}\n", "expected one totem section, found 0"),
        ("totem {\n}\ntotem {\n}\n", "expected one totem section, found 2"),
        ("totem {\n}\n}\n", "closes no section"),
        ("totem {\n", "never closed"),
    ],
)
def test_an_unsafe_file_is_refused(text: str, match: str) -> None:
    with pytest.raises(hb.CorosyncConfError, match=match):
        hb.apply_heartbeat(text, 10000)


def test_a_key_outside_any_section_is_ignored() -> None:
    out = hb.apply_heartbeat("stray: 1\ntotem {\n}\n", 10000)
    assert out.splitlines()[0] == "stray: 1"


# --- the module entry point ---------------------------------------------------------


class FakeModule:
    """Enough of AnsibleModule for main(): params, check mode, exits, atomic_move."""

    check_mode_default = False

    def __init__(self, argument_spec: dict[str, Any], supports_check_mode: bool) -> None:
        assert supports_check_mode
        assert argument_spec["token"] == {"type": "int", "required": True}
        self.params = dict(FakeModule.params_for_test)
        self.check_mode = FakeModule.check_mode_default
        self.result: dict[str, Any] = {}
        self.cleanup: list[str] = []
        FakeModule.last = self

    params_for_test: dict[str, Any] = {}
    last: FakeModule

    def fail_json(self, **kwargs: Any) -> None:
        self.result = {"failed": True, **kwargs}

    def exit_json(self, **kwargs: Any) -> None:
        self.result = kwargs

    def add_cleanup_file(self, path: str) -> None:
        self.cleanup.append(path)

    def atomic_move(self, src: str, dest: str) -> None:
        Path(src).replace(dest)


def _run_main(
    monkeypatch: pytest.MonkeyPatch, path: Path, *, check_mode: bool = False
) -> FakeModule:
    monkeypatch.setattr(hb, "AnsibleModule", FakeModule)
    monkeypatch.setattr(FakeModule, "params_for_test", {"path": str(path), "token": 10000})
    monkeypatch.setattr(FakeModule, "check_mode_default", check_mode)
    hb.main()
    return FakeModule.last


def test_main_writes_the_file_and_reports_the_values(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    conf = tmp_path / "corosync.conf"
    conf.write_text(RDQM_CONF, encoding="utf-8")
    module = _run_main(monkeypatch, conf)
    assert module.result["changed"] is True
    assert module.result["links"] == [0]
    assert module.result["knet_ping_timeout"] == "5000"
    assert module.result["knet_ping_interval"] == "500"
    assert module.result["knet_pong_count"] == "2"
    assert conf.read_text(encoding="utf-8") == hb.apply_heartbeat(RDQM_CONF, 10000)
    assert not Path(module.cleanup[0]).exists()

    again = _run_main(monkeypatch, conf)
    assert again.result["changed"] is False


def test_main_in_check_mode_leaves_the_file(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    conf = tmp_path / "corosync.conf"
    conf.write_text(RDQM_CONF, encoding="utf-8")
    module = _run_main(monkeypatch, conf, check_mode=True)
    assert module.result["changed"] is True
    assert conf.read_text(encoding="utf-8") == RDQM_CONF


def test_main_fails_loud_on_a_missing_file(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    module = _run_main(monkeypatch, tmp_path / "absent.conf")
    assert module.result["failed"] is True
    assert "absent.conf" in module.result["msg"]


def test_main_fails_loud_on_an_unsafe_file(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    conf = tmp_path / "corosync.conf"
    conf.write_text("quorum {\n}\n", encoding="utf-8")
    module = _run_main(monkeypatch, conf)
    assert module.result["failed"] is True
    assert "totem" in module.result["msg"]


