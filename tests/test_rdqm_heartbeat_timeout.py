def _tasks() -> list[dict[str, Any]]:
    tasks: list[dict[str, Any]] = yaml.safe_load(TASKS.read_text(encoding="utf-8"))
    return tasks


def _task(name: str) -> dict[str, Any]:
    (task,) = [t for t in _tasks() if t.get("name") == name]
    return task


BEFORE = "read the running corosync heartbeat timeout (before)"
LIMITS = "the heartbeat timeout is within IBM's limits (fail loud)"
EDIT = "set the heartbeat timeout in corosync.conf (IBM's token and knet values)"
WINDOW = "apply the heartbeat timeout across the site in Pacemaker maintenance mode"
AFTER = "read the running corosync heartbeat timeout (after)"
CHECK = "corosync runs the configured heartbeat timeout (fail loud)"
LINKS = "read the running corosync heartbeat link settings"
LINK_CHECK = "corosync runs IBM's knet values on each heartbeat link (fail loud)"
STONITH_CHECK = "RDQM's cluster-wide setup ran: stonith-enabled is false (fail loud)"


def test_default_is_ibms_vm_recommendation() -> None:
    defaults = yaml.safe_load(DEFAULTS.read_text(encoding="utf-8"))
    assert defaults["rdqm_heartbeat_token_ms"] == 10000
    source = DEFAULTS.read_text(encoding="utf-8")
    assert "SSYHRD_10.0.0/configure/heartbeat_timeout.html" in source


def test_heartbeat_runs_after_rdqmadm_and_in_ibms_order() -> None:
    names = [t.get("name") for t in _tasks()]
    order = [STONITH_CHECK, BEFORE, LIMITS, EDIT, WINDOW, AFTER, CHECK, LINKS, LINK_CHECK]
    assert [names.index(n) for n in order] == sorted(names.index(n) for n in order)


def test_the_editor_module_is_given_the_role_value() -> None:
    task = _task(EDIT)
    assert "rdqm_heartbeat_token_ms" in task["rdqm_corosync_heartbeat"]["token"]
    assert task.get("become") is True
    assert task.get("register")


def test_maintenance_window_follows_ibms_procedure() -> None:
    window = _task(WINDOW)
    # Idempotency gate: only when some node of the site needs a restart.
    assert "rdqm_hb_restart" in window["when"]
    assert "ansible_play_hosts" in window["when"]
    steps = window["block"]
    assert steps[0]["ansible.builtin.command"]["argv"] == ["crm", "maintenance", "on"]
    assert steps[0].get("run_once") is True
    assert steps[1]["ansible.builtin.systemd_service"] == {
        "name": "corosync",
        "state": "restarted",
    }
    assert "run_once" not in steps[1]  # every node of the site
    wait = steps[2]
    assert "maintenance-mode" in wait["ansible.builtin.command"]["argv"]
    assert wait["retries"] * wait["delay"] > 0
    assert steps[3]["ansible.builtin.command"]["argv"] == ["crm", "maintenance", "off"]
    assert steps[3].get("run_once") is True
    assert len(steps) == 4


def test_the_restart_decision_covers_an_unrestarted_edit() -> None:
    (note,) = [t for t in _tasks() if "rdqm_hb_restart" in t.get("ansible.builtin.set_fact", {})]
    expr = note["ansible.builtin.set_fact"]["rdqm_hb_restart"]
    assert "rdqm_hb_conf.changed" in expr
    assert "rdqm_hb_running_ms" in expr


def test_running_values_are_read_with_ibms_check() -> None:
    for name, key in ((BEFORE, "totem.token"), (AFTER, "totem.token"), (LINKS, "totem.interface.")):
        task = _task(name)
        assert task["ansible.builtin.command"]["argv"] == ["corosync-cmapctl", key]
        assert task.get("changed_when") is False


def test_checks_fail_loud() -> None:
    for name in (LIMITS, CHECK, LINK_CHECK):
        task = _task(name)
        assert task["ansible.builtin.assert"].get("fail_msg")
        for key in (*SOFTENERS, "until"):
            assert key not in task, f"{name!r} must not carry {key!r}"
    for name in (BEFORE, EDIT, AFTER, LINKS):
        for key in SOFTENERS:
            assert key not in _task(name)
    limits = " ".join(_task(LIMITS)["ansible.builtin.assert"]["that"])
    assert "3000" in limits
    assert "120000" in limits
    assert "4 *" in limits
    loop = _task(LINK_CHECK)["loop"]
    for key in ("knet_ping_timeout", "knet_ping_interval", "knet_pong_count"):
        assert key in loop
